#!/usr/bin/env python
"""Compares the gold of a frozen tier (Caladrius) with an independent NCA by PKNCA (T-101, FROZEN_SET.md §5.4).

bench/pknca/frozen_nca_pknca.R writes the PKNCA values; this script compares them, parameter by parameter, with the
`ground_truth.nca` of every meta.json at the tolerance of Caladrius's own conformance tests against PKNCA
(NCA_VS_PKNCA: relative 1e-6, absolute 1e-12 at an expected zero; caladrius docs/validation.md §2.3), and writes
CHECK.md and check.json next to the PKNCA output. Every gold value is classed:

  agree            both computed, within tolerance
  differ           both computed, beyond tolerance (the case freeze waits until each one is explained, §5.4)
  gold only        Caladrius computed it, PKNCA returned nothing for it (or the parameter is not asked of PKNCA)
  PKNCA only       PKNCA computed it, Caladrius reported it as not calculated (its reason is printed)

  Rscript bench/pknca/frozen_nca_pknca.R bench/frozen/demo/exercises bench/frozen/demo/pknca/pknca.csv     (R, PKNCA 0.12.1)
  python bench/pknca_check.py --tier demo
"""
import argparse, collections, csv, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
AGENT = os.path.dirname(HERE)
if AGENT not in sys.path: sys.path.insert(0, AGENT)
from bench import make_exercises as mk, make_frozen as mf  # noqa: E402

REL, ABS_AT_ZERO = 1e-6, 1e-12
METHODS = ("linear", "lin_up_log_down")

def pknca_dir(tier): return os.path.join(mf.tier_dir(tier), "pknca")

def load_pknca(path):
    """{(exercise, method, parameter): value or None}"""
    out = {}
    with open(path, encoding="utf-8", newline="") as f:
        for r in csv.DictReader(f):
            out[(r["exercise"], r["method"], r["parameter"])] = float(r["value"]) if r["value"] not in ("", "NA", "NaN") else None
    return out

def within(gold, other):
    if gold == 0: return abs(other) <= ABS_AT_ZERO
    return abs(other - gold) <= REL * abs(gold)

def rel_gap(gold, other):
    return abs(other - gold) / abs(gold) if gold else abs(other - gold)

def compare(tier, pknca_csv=None):
    pk = load_pknca(pknca_csv or os.path.join(pknca_dir(tier), "pknca.csv"))
    rows, by_param = [], collections.defaultdict(collections.Counter)
    for d in mf.list_exercises(tier):
        meta, _ = mk.load(d)
        for m in METHODS:
            g = meta["ground_truth"]["nca"][m]
            asked = {p for (e, mm, p) in pk if e == meta["id"] and mm == m}
            for p, v in sorted(g["parameters"].items()):
                o = pk.get((meta["id"], m, p))
                if o is None: cls = "gold only"
                elif within(v["value"], o): cls = "agree"
                else: cls = "differ"
                rows.append({"exercise": meta["id"], "method": m, "parameter": p, "class": cls, "gold": v["value"], "unit": v["unit"],
                             "pknca": o, "rel_gap": None if o is None else rel_gap(v["value"], o), "asked": p in asked})
                by_param[p][cls] += 1
            for p, why in sorted(g["not_calculated"].items()):
                o = pk.get((meta["id"], m, p))
                if o is not None and why != "not_applicable_to_route":
                    rows.append({"exercise": meta["id"], "method": m, "parameter": p, "class": "PKNCA only", "gold": None,
                                 "pknca": o, "reason": why, "asked": True})
                    by_param[p]["PKNCA only"] += 1
    both = [r for r in rows if r["class"] in ("agree", "differ")]
    worst = max(both, key=lambda r: r["rel_gap"]) if both else None
    counts = collections.Counter(r["class"] for r in rows)
    with open(os.path.join(os.path.dirname(pknca_csv or os.path.join(pknca_dir(tier), "pknca.csv")), "pknca.json"), encoding="utf-8") as f:
        info = json.load(f)
    return {"tier": tier, "tolerance": {"relative": REL, "absolute_at_zero": ABS_AT_ZERO}, "versions": info.get("versions"),
            "exercises": len(mf.list_exercises(tier)), "counts": dict(counts),
            "worst": None if worst is None else {k: worst[k] for k in ("exercise", "method", "parameter", "gold", "pknca", "rel_gap")},
            "by_parameter": {p: dict(c) for p, c in sorted(by_param.items())},
            "differ": [r for r in rows if r["class"] == "differ"], "pknca_only": [r for r in rows if r["class"] == "PKNCA only"],
            "gold_only_parameters": sorted({r["parameter"] for r in rows if r["class"] == "gold only"})}

def render_md(c):
    n = c["counts"]; both = n.get("agree", 0) + n.get("differ", 0)
    L = [f"# PKNCA cross-check of the gold, tier {c['tier']}", "",
         f"Generated by `bench/pknca_check.py` from `pknca.csv` ({c['versions'].get('R')}, PKNCA {c['versions'].get('PKNCA')}). "
         f"Tolerance: relative {c['tolerance']['relative']:g}, absolute {c['tolerance']['absolute_at_zero']:g} at an expected zero, "
         "the tolerance of Caladrius's own conformance tests against PKNCA.", "",
         f"- exercises: {c['exercises']}, both AUC methods",
         f"- values computed by both: {both}; within tolerance **{n.get('agree', 0)} / {both}**; beyond tolerance {n.get('differ', 0)}",
         f"- largest relative gap: {c['worst']['rel_gap']:.2e} ({c['worst']['exercise']}, {c['worst']['method']}, {c['worst']['parameter']})"
         if c["worst"] else "- largest relative gap: n/a",
         f"- gold values without a PKNCA counterpart: {n.get('gold only', 0)} (parameters: {', '.join(c['gold_only_parameters']) or 'none'})",
         f"- values PKNCA computed and Caladrius reported as not calculated: {n.get('PKNCA only', 0)}", ""]
    if c["differ"]:
        L += ["## Beyond tolerance", "", "| exercise | method | parameter | gold | PKNCA | relative gap |", "|---|---|---|---|---|---|"]
        L += [f"| {r['exercise']} | {r['method']} | {r['parameter']} | {r['gold']:.10g} | {r['pknca']:.10g} | {r['rel_gap']:.2e} |" for r in c["differ"]]
        L.append("")
    if c["pknca_only"]:
        L += ["## Computed by PKNCA only", "", "| exercise | method | parameter | PKNCA | Caladrius's reason |", "|---|---|---|---|---|"]
        L += [f"| {r['exercise']} | {r['method']} | {r['parameter']} | {r['pknca']:.10g} | {r['reason']} |" for r in c["pknca_only"]]
        L.append("")
    L += ["## By parameter", "", "| parameter | agree | differ | gold only | PKNCA only |", "|---|---|---|---|---|"]
    L += [f"| {p} | {v.get('agree', 0)} | {v.get('differ', 0)} | {v.get('gold only', 0)} | {v.get('PKNCA only', 0)} |" for p, v in c["by_parameter"].items()]
    return "\n".join(L) + "\n"

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--tier", default="demo", choices=sorted(mf.TIERS))
    ap.add_argument("--pknca", default=None, help="the PKNCA output (default bench/frozen/<tier>/pknca/pknca.csv)")
    a = ap.parse_args()
    c = compare(a.tier, a.pknca)
    out = os.path.dirname(a.pknca or os.path.join(pknca_dir(a.tier), "pknca.csv"))
    with open(os.path.join(out, "check.json"), "w", encoding="utf-8", newline="\n") as f: json.dump(c, f, ensure_ascii=False, indent=1); f.write("\n")
    with open(os.path.join(out, "CHECK.md"), "w", encoding="utf-8", newline="\n") as f: f.write(render_md(c))
    n = c["counts"]
    print(f"agree {n.get('agree', 0)}, differ {n.get('differ', 0)}, gold only {n.get('gold only', 0)}, PKNCA only {n.get('PKNCA only', 0)}")
    sys.exit(1 if n.get("differ") else 0)

if __name__ == "__main__":
    main()
